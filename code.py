# ขั้นที่ 2: ลงมือเขียนและดัดแปลงโค้ด
shape = input("เลือกรูปทรง (1: สี่เหลี่ยม, 2: สามเหลี่ยม): ")
กว้าง = float(input("ป้อนความกว้าง/ฐาน: "))
ยาว = float(input("ป้อนความยาว/สูง: "))

if กว้าง <= 0 or ยาว <= 0:
    print("ข้อผิดพลาด: ค่าต้องมากกว่า 0!")
else:
    if shape == "1":
        พื้นที่ = กว้าง * ยาว
        print("พื้นที่สี่เหลี่ยมคือ:", พื้นที่)
    elif shape == "2":
        พื้นที่ = 0.5 * กว้าง * ยาว
        print("พื้นที่สามเหลี่ยมคือ:", พื้นที่)
    else:
        print("เลือกเมนูไม่ถูกต้อง!")